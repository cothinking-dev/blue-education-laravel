            <h2>Policy Overview</h2>
            <p>Blue Education maintains commitment to &ldquo;a safe and respectful environment for all our employees&rdquo; and has implemented a Zero Tolerance policy applicable to customers, clients, and those accessing services.</p>

            <h2>1. Definition of Abusive Behaviour</h2>
            <p>The policy defines abusive conduct as &ldquo;any action, language, or gesture that is intended to intimidate, belittle, threaten, discriminate against, or harm the physical or emotional well-being of our employees.&rdquo;</p>
            <p>Specific examples include:</p>
            <ul>
                <li>Verbal/written abuse (yelling, profanity, derogatory comments)</li>
                <li>Physical aggression (assault, pushing, physical harm)</li>
                <li>Sexual harassment or inappropriate advances</li>
                <li>Discrimination based on protected characteristics (race, gender, religion, age, disability, nationality)</li>
                <li>Threats of violence (explicit or implied)</li>
                <li>Cyberbullying or online harassment</li>
                <li>Other conduct deemed abusive by the company</li>
            </ul>

            <h2>2. Reporting Process</h2>
            <p>Employees experiencing or witnessing abusive behaviour should report to supervisors, managers, or HR representatives. The company maintains confidentiality and provides &ldquo;no negative consequences or retaliation for reporting incidents.&rdquo;</p>

            <h2>3. Investigation and Consequences</h2>
            <p>Actions may include warnings, service access restriction/termination, involving legal authorities for criminal offences, or pursuing civil remedies.</p>

            <h2>4. Communication of Policy</h2>
            <p>The policy is communicated through signs, service agreements, customer interactions, and educational materials.</p>

            <h2>5. Continuous Improvement</h2>
            <p>Blue Education commits to reviewing and updating policies based on employee feedback and industry practices.</p>
